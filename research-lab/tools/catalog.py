#!/usr/bin/env python3
"""Validate the research catalog and render navigation. Never executes study code."""
from __future__ import annotations
import argparse
from datetime import date
import json
import os
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path('research-lab/problems/catalog.json')
VALIDITY = {'ANALYTICAL_PROOF','EXACT_FINITE_CERTIFICATE','COUNTEREXAMPLE',
            'CONDITIONAL_DERIVATION','CONJECTURE','CORRECTION','NO_ADVANCE',
            'BLOCKED','NUMERICAL_LEAD','SUSPENDED','RETRACTED'}
FORMAL = {'UNFORMALIZED','LEAN_PENDING','LEAN_VERIFIED_AT_COMMIT'}
LITERATURE = {'KNOWN','PRIORITY_UNCHECKED','CANDIDATE_NOVELTY'}
SHA = re.compile(r'[0-9a-f]{40}')
SLUG = re.compile(r'[a-z0-9]+(?:-[a-z0-9]+)*')
LINK = re.compile(r'\[[^\]\n]*\]\(([^\s()]+)\)')
STAMP = '<!-- Generated by research-lab/tools/catalog.py. Edit catalog.json, not this file. -->'


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def local_path(root: Path, raw: str) -> Path:
    require(isinstance(raw,str) and bool(raw), 'Expected a nonempty local path')
    parsed = urlsplit(raw)
    require(not parsed.scheme and not parsed.netloc, f'Expected local path: {raw}')
    path = Path(unquote(parsed.path))
    require(not path.is_absolute() and '..' not in path.parts, f'Unsafe catalog path: {raw}')
    resolved = (root/path).resolve()
    require(resolved.is_relative_to(root.resolve()), f'Path escapes repository: {raw}')
    require(resolved.exists(), f'Missing catalog target: {raw}')
    return resolved


def text(value: object, label: str) -> str:
    require(isinstance(value,str) and bool(value.strip()), f'Missing text: {label}')
    require('\n' not in value and '|' not in value, f'Use single-line table-safe text: {label}')
    return value


def validate(data: dict, root: Path) -> None:
    require(data.get('schema_version') == 1, 'Unsupported catalog schema')
    require(SHA.fullmatch(data.get('snapshot_commit','')) is not None, 'Missing snapshot commit')
    date.fromisoformat(data['navigation_updated'])
    require(isinstance(data.get('problems'),list) and data['problems'], 'No problems registered')
    ids, result_ids, indexed = set(), set(), set()
    for p in data['problems']:
        pid = text(p.get('id'), 'problem.id')
        require(SLUG.fullmatch(pid) is not None and pid not in ids, f'Duplicate/invalid problem: {pid}')
        ids.add(pid)
        require(p.get('status') in {'ACTIVE','RETAINED','PARKED'}, f'Invalid project status: {pid}')
        if p.get('kind') == 'erdos':
            n = p.get('number')
            require(type(n) is int and n > 0 and pid == f'erdos-{n}', f'Incorrect Erdős number: {pid}')
        else:
            require(p.get('kind') == 'related' and p.get('number') is None,
                    f'Related branches must not invent a problem number: {pid}')
        for key in ['title','summary','question','boundary','next_question','falsifier']:
            text(p.get(key), f'{pid}.{key}')
        for resource in p.get('resources',[]):
            text(resource.get('label'), 'resource.label')
            local_path(root,resource['path'])
        require(isinstance(p.get('results'),list), f'Missing result list: {pid}')
        for r in p['results']:
            rid = text(r.get('id'),'result.id')
            require(rid not in result_ids, f'Duplicate result: {rid}')
            result_ids.add(rid)
            date.fromisoformat(r['date'])
            text(r.get('title'),f'{rid}.title'); text(r.get('scope'),f'{rid}.scope')
            require(r.get('validity') in VALIDITY, f'Invalid validity: {rid}')
            require(r.get('formal_status') in FORMAL, f'Invalid formal status: {rid}')
            require(r.get('literature') in LITERATURE, f'Invalid literature status: {rid}')
            proof=local_path(root,r['proof'])
            require(proof.is_file() and proof.suffix == '.md', f'Proof note must be Markdown: {rid}')
            require(r['proof'] not in indexed, f'Proof registered twice: {rid}')
            indexed.add(r['proof'])
            require(isinstance(r.get('code'),list), f'Expected source-link list: {rid}')
            if r['validity'] == 'EXACT_FINITE_CERTIFICATE':
                require(bool(r['code']), f'Finite certificate needs executable source: {rid}')
            for path in r['code']:
                require(local_path(root,path).is_file(), f'Source is not a file: {path}')
            require(SHA.fullmatch(r.get('evidence_commit','')) is not None, f'Missing evidence commit: {rid}')
            run=r.get('evidence_run')
            if run is not None:
                require(isinstance(run,str) and re.fullmatch(r'https://github\.com/[^/]+/[^/]+/actions/runs/[0-9]+',run) is not None,
                        f'Invalid run evidence: {rid}')
            if r['validity'] == 'EXACT_FINITE_CERTIFICATE':
                require(bool(run), f'Finite certificate needs recorded run evidence: {rid}')
            if r['formal_status'] == 'LEAN_VERIFIED_AT_COMMIT':
                f=r.get('formal_evidence',{})
                require(SHA.fullmatch(f.get('commit','')) is not None, f'Missing Lean commit: {rid}')
                require(local_path(root,f.get('path','')).suffix == '.lean', f'Missing Lean file: {rid}')
                text(f.get('theorem'),f'{rid}.theorem')
    require(sum(p['status']=='ACTIVE' for p in data['problems']) <= 1,
            'Keep at most one active problem in this notebook')
    historical={str(p.relative_to(root)) for p in (root/'research-lab/studies').glob('*/proofs/*.md')}
    require(historical <= indexed, f'Unindexed historical proofs: {sorted(historical-indexed)}')
    for m in data.get('maintenance',[]):
        date.fromisoformat(m['date'])
        require(m.get('kind') == 'INFRASTRUCTURE','Maintenance is not mathematical progress')
        text(m.get('summary'),'maintenance.summary'); local_path(root,m['path'])


def link(source: str, target: str, label: str) -> str:
    p=urlsplit(target)
    relative=Path(os.path.relpath(p.path,Path(source).parent)).as_posix()
    if p.fragment: relative += '#'+p.fragment
    return f'[{label}]({relative})'


def render(data: dict) -> dict[str,str]:
    pages={}
    index='research-lab/problems/README.md'
    lines=[STAMP,'','# Problem directory','',
           '[Lab](../README.md) · [Progress](../PROGRESS.md) · [Verification](../REPRODUCING.md)','',
           'Project labels describe work in this repository, not externally verified open/solved status.','',
           '| Problem | Project focus | Latest registered result | Next question |','|---|---|---|---|']
    for p in data['problems']:
        target=f"research-lab/problems/{p['id']}/README.md"
        latest=max((r['date'] for r in p['results']),default='No imported result')
        label=(f"Erdős #{p['number']}: " if p['number'] else '')+p['title']
        lines.append(f"| {link(index,target,label)} | {p['status']} | {latest} | {p['next_question']} |")
        body=[STAMP,'',f'# {label}','',
              '[All problems](../README.md) · [Lab](../../README.md) · [Progress](../../PROGRESS.md) · [Contribute](../../CONTRIBUTING.md)','',
              f"**Project focus: {p['status']}.** {p['summary']}",'',
              '## The question','',p['question'],'',
              '## Read this first','',p['boundary'],'',
              '## Results and evidence','']
        if p['results']:
            body+=['| Date | Result | Validity | Proof and code |','|---|---|---|---|']
            for r in sorted(p['results'],key=lambda r:(r['date'],r['id']),reverse=True):
                refs=[link(target,r['proof'],'Proof')]+[link(target,s,f'Code {i+1}') for i,s in enumerate(r['code'])]
                body.append(f"| {r['date']} | {r['title']} | {r['validity']} | {' · '.join(refs)} |")
            body+=['','<details>','<summary>Exact scope and evidence provenance</summary>','']
            for r in sorted(p['results'],key=lambda r:(r['date'],r['id']),reverse=True):
                body += [f"### {r['title']}",'',r['scope'],'',
                         f"Formalization: **{r['formal_status']}**. Literature: **{r['literature']}**.",
                         (f"Recorded computational reproduction: [run]({r['evidence_run']}) at `{r['evidence_commit']}`. This is historical evidence, not a claim about today's CI." if r.get('evidence_run') else f"Evidence baseline: `{r['evidence_commit']}`. No CI execution is claimed for this entry. Inspect the proof and its assumptions."),'']
            body+=['</details>','']
        else:
            body+=['No numerical result is imported into this catalog for this lane. Original work remains available through the links below.','']
        body+=['## Next bounded question','',p['next_question'],'',f"**Discriminating test:** {p['falsifier']}",'',
               '## Navigate','']
        body += [link(target,r['path'],r['label'])+'  ' for r in p['resources']]
        body+=['','[Reproduce the existing studies](../../REPRODUCING.md). A new catalog entry does not automatically run a new verifier.','',
               '## Versioning','',
               'New work goes in `runs/YYYY-MM-DD-short-name/` under this problem. Keep proof, code and receipts together; register them in `../catalog.json`. Existing dated study paths are stable.', '',
               'Original lab contributions follow the [scoped MIT license](../../LICENSE). References and third-party material retain their own terms.','']
        pages[target]='\n'.join(body)
    lines+=['','[Edit the catalog](catalog.json) and regenerate with `python3 research-lab/tools/catalog.py --write`.','',
            f"Navigation updated: {data['navigation_updated']}. This date is not a mathematical discovery date.",'']
    pages[index]='\n'.join(lines)
    progress='research-lab/PROGRESS.md'
    out=[STAMP,'','# Progress log','',
         '[Lab](README.md) · [Problems](problems/README.md) · [Claim status](STATUS.md)','',
         'Mathematical entries below are existing registered studies, not newly rediscovered results. Click a proof for exact assumptions.','',
         '| Date | Problem | Contribution | Validity |','|---|---|---|---|']
    entries=[(p,r) for p in data['problems'] for r in p['results']]
    for p,r in sorted(entries,key=lambda pr:(pr[1]['date'],pr[1]['id']),reverse=True):
        out.append(f"| {r['date']} | {link(progress,'research-lab/problems/'+p['id']+'/README.md',p['id'])} | {link(progress,r['proof'],r['title'])} | {r['validity']} |")
    out+=['','## Infrastructure, separate from mathematical results','']
    for m in sorted(data.get('maintenance',[]),key=lambda m:m['date'],reverse=True):
        out += [f"**{m['date']} · {m['kind']}:** {link(progress,m['path'],m['summary'])}",'']
    out+=['## Read verification correctly','',
          '[Current workflow](https://github.com/Arnie016/erdos170/actions/workflows/math-research-ci.yml) · [Lean scope](lean/README.md) · [Contributing](CONTRIBUTING.md)','',
          'No activity or result is invented for missing days. Commits, failed runs and corrected claims remain separate kinds of evidence.','']
    pages[progress]='\n'.join(out)
    return pages


def check_links(root: Path, files: dict[str,str]) -> None:
    for name, body in files.items():
        for raw in LINK.findall(body):
            u=urlsplit(raw)
            if u.scheme or u.netloc or not u.path: continue
            destination=(root/name).parent/unquote(u.path)
            require(destination.resolve().is_relative_to(root.resolve()), f'Link escapes repo: {name}: {raw}')
            require(destination.exists(), f'Broken local link: {name}: {raw}')


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write',action='store_true'); mode.add_argument('--check',action='store_true')
    args=parser.parse_args()
    try:
        data=json.loads((ROOT/CATALOG).read_text())
        validate(data,ROOT); pages=render(data)
        for name, content in pages.items():
            path=ROOT/name
            if args.write:
                path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
            else:
                require(path.exists() and path.read_text()==content, f'Stale generated navigation: {name}; run --write')
        checks=dict(pages)
        for name in ['README.md','research-lab/README.md','research-lab/CONTRIBUTING.md']:
            checks[name]=(ROOT/name).read_text()
        check_links(ROOT,checks)
        print(f"PASS: {len(data['problems'])} problem pages, {sum(len(p['results']) for p in data['problems'])} registered studies, local links and generated pages")
        return 0
    except (OSError,ValueError,KeyError,TypeError) as e:
        print(f'FAIL: {e}')
        return 1

if __name__=='__main__':
    raise SystemExit(main())
